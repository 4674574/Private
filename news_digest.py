GENERIC_DIGEST = "资讯：当日新闻中的一条，具体内容可点击标题查看原文"


def find_digest(title: str, source_key: str = "") -> str:
    """按关键词最长匹配找要点；找不到就用按源兜底。"""
    best = None
    best_len = -1
    for key, val in DIGEST.items():
        if key in title and len(key) > best_len:
            best, best_len = val, len(key)
    if best:
        return best
    return SOURCE_DIGEST.get(source_key, GENERIC_DIGEST)


def brief_title(title: str) -> str:
    """把标题压缩成短语（去掉栏目前缀和过长后缀），用于要点行首。"""
    import re
    t = re.sub(r"^(视频丨|视频\||直播回放[:：]?|独家[:：]|快讯[:：]|组图丨|图集丨)+", "", title or "")
    t = re.sub(r"\s+", " ", t).strip()
    return t


